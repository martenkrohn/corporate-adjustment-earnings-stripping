# Direct table, figure, and machine-readable output helpers.

# `ensure_output_directories()` creates every supplied path recursively and
# returns the paths invisibly so directory setup can remain in a pipeline.
ensure_output_directories <- function(paths) {
  for (path in unname(paths)) dir.create(path, recursive = TRUE, showWarnings = FALSE)
  invisible(paths)
}

# `write_csv_artifact()` creates the destination directory and writes a CSV
# with blank fields for missing values. It returns the path invisibly.
write_csv_artifact <- function(data, path) {
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  readr::write_csv(data, path, na = "")
  invisible(path)
}

# `latex_escape()` protects characters with special meaning in LaTeX so labels
# and text values cannot break a generated table.
latex_escape <- function(x) {
  x <- as.character(x)
  x <- gsub("\\\\", "\\\\textbackslash{}", x)
  x <- gsub("([#$%&_{}])", "\\\\\\1", x, perl = TRUE)
  x <- gsub("~", "\\\\textasciitilde{}", x, fixed = TRUE)
  x
}

# `format_number()` and `format_integer()` apply consistent display formatting
# and represent missing values with an en-dash-style double hyphen for LaTeX.
format_number <- function(x, digits = 3L) {
  ifelse(is.na(x), "--", formatC(x, format = "f", digits = digits, big.mark = ","))
}

# `format_integer()` adds thousands separators without decimal places.
format_integer <- function(x) ifelse(is.na(x), "--", format(as.integer(x), big.mark = ",", scientific = FALSE))

# `write_latex_table()` converts an ordinary data frame into a booktabs-style
# LaTeX table with caption, label, optional notes, and safe text escaping.
write_latex_table <- function(data, path, caption, label, note = NULL, align = NULL, escape = TRUE) {
  if (is.null(align)) align <- paste0("l", paste(rep("r", max(ncol(data) - 1L, 0L)), collapse = ""))
  values <- as.data.frame(data, stringsAsFactors = FALSE, check.names = FALSE)
  if (escape) {
    values[] <- lapply(values, latex_escape)
    headers <- latex_escape(names(values))
  } else {
    headers <- names(values)
  }
  row_lines <- if (nrow(values) == 0L) character() else apply(values, 1L, function(row) paste0(paste(row, collapse = " & "), " \\\\"))
  lines <- c(
    "% Automatically generated by the linear analysis package.",
    "\\begin{table}[htbp]", "\\centering",
    sprintf("\\caption{%s}", caption), sprintf("\\label{%s}", label),
    sprintf("\\begin{tabular}{%s}", align), "\\toprule",
    paste0(paste(headers, collapse = " & "), " \\\\"), "\\midrule",
    row_lines, "\\bottomrule", "\\end{tabular}"
  )
  if (!is.null(note) && nzchar(note)) lines <- c(lines, sprintf("\\parbox{\\textwidth}{\\footnotesize \\textit{Notes:} %s}", note))
  lines <- c(lines, "\\end{table}")
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  writeLines(lines, path, useBytes = TRUE)
  invisible(path)
}

# `clean_etable_tex()` standardizes a few fixest-generated labels before the
# model table is written into the thesis-compatible LaTeX fragment.
clean_etable_tex <- function(x) {
  x <- gsub("\\\\# Firm", "Firms", x)
  x <- gsub("\\\\# Year", "Years", x)
  x <- gsub("Year \\([0-9,]+\\)", "Year", x)
  sub("[[:blank:]]+$", "", x)
}

# `write_model_table()` asks fixest to assemble a regression table with the
# requested labels, fit statistics, significance markers, and explanatory note.
write_model_table <- function(models, path, title, label, headers, dictionary, note, fontsize = "small") {
  table <- fixest::etable(
    models, tex = TRUE, title = title, label = label, headers = headers,
    depvar = FALSE, dict = dictionary, order = "Treat", fixef_sizes = TRUE,
    fixef_sizes.simplify = FALSE, fitstat = ~ n + ar2 + wr2,
    digits = 4, digits.stats = 3,
    signif.code = c("***" = 0.01, "**" = 0.05, "*" = 0.10),
    style.tex = fixest::style.tex("base", tablefoot = FALSE),
    fontsize = fontsize, notes = paste0("\\textit{Notes:} ", note)
  )
  dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
  writeLines(c("% Automatically generated by the linear analysis package.", clean_etable_tex(table)), path, useBytes = TRUE)
  invisible(path)
}

# Join each reported treatment estimate to its model diagnostics. The export
# script supplies the result object and the treatment term to retain.
model_table <- function(result, treatment_term) {
  result$coefficients |>
    dplyr::filter(.data$term == treatment_term) |>
    dplyr::left_join(result$fit_stats, by = intersect(
      c("model_id", "control_set", "control_set_id", "variant_id", "regime_id"),
      intersect(names(result$coefficients), names(result$fit_stats))
    ))
}

# Write one optional machine-readable audit CSV and return a compact record of
# its filename and dimensions.
write_generated_model <- function(data, filename, output_dir) {
  readr::write_csv(data, file.path(output_dir, filename), na = "")
  tibble::tibble(file = filename, generated_rows = nrow(data), generated_columns = ncol(data))
}

# `build_descriptive_artifacts()` prepares the five descriptive data frames.
# The numbered script decides which filenames, captions, and labels they use.
build_descriptive_artifacts <- function(analysis_data, audits, policy_path) {
  # Select and label only variables available in the main analysis sample.
  variable_map <- tibble::tribble(
    ~variable, ~label, ~role,
    "dta", "Debt-to-assets", "Outcome",
    "ln_equity", "Log equity", "Outcome component",
    "ln_current_debt", "Log current debt", "Outcome component",
    "ln_longterm_debt", "Log long-term debt", "Outcome component",
    "earnvol", "Adjusted earnings volatility", "Outcome",
    "unadj_earnvol", "Unadjusted earnings volatility", "Outcome",
    "cash_assets", "Cash/assets", "Outcome",
    "log_assets", "Log assets", "Firm control",
    "profitability", "EBIT/assets", "Firm control",
    "roa_ebitda", "EBITDA/assets", "Firm control",
    "tangibility", "Tangibility", "Firm control",
    "growth", "Log sales growth", "Firm control",
    "growth_options", "Country-sector sales growth", "Firm control"
  ) |>
    dplyr::filter(.data$variable %in% names(analysis_data))
  # Summarize non-missing values with the display precision used in the thesis.
  summary <- purrr::pmap_dfr(variable_map, function(variable, label, role) {
    value <- analysis_data[[variable]]
    tibble::tibble(Role = role, Variable = label, Observations = format_integer(sum(!is.na(value))),
                   Mean = format_number(mean(value, na.rm = TRUE)), SD = format_number(stats::sd(value, na.rm = TRUE)),
                   Median = format_number(stats::median(value, na.rm = TRUE)), Min = format_number(min(value, na.rm = TRUE)),
                   Max = format_number(max(value, na.rm = TRUE)))
  })
  # Reconstruct sample flow from stored audit logs instead of hard-coding counts.
  cleaning_steps <- audits$clean_filter |>
    dplyr::filter(.data$step %in% c("restrict_raw_year_window", "exclude_financial_sector", "enforce_positive_assets")) |>
    dplyr::mutate(order = match(.data$step, c("restrict_raw_year_window", "exclude_financial_sector", "enforce_positive_assets"))) |>
    dplyr::arrange(.data$order)
  sample_steps <- audits$sample_filter |>
    dplyr::filter(.data$step %in% c("restrict_year_window", "require_pre_post_support")) |>
    dplyr::mutate(order = match(.data$step, c("restrict_year_window", "require_pre_post_support"))) |>
    dplyr::arrange(.data$order)
  flow <- dplyr::bind_rows(
    tibble::tibble(step = "Imported Orbis export", observations = audits$import_counts$observations,
                   firms = audits$import_counts$firms, countries = audits$import_counts$countries),
    dplyr::transmute(cleaning_steps, step = dplyr::recode(.data$step,
      restrict_raw_year_window = "Retain accounting years 2012--2023",
      exclude_financial_sector = "Exclude NACE 64--66 firms",
      enforce_positive_assets = "Require positive total assets"),
      observations = .data$obs_after, firms = .data$firms_after, countries = .data$countries_after),
    dplyr::transmute(sample_steps, step = dplyr::recode(.data$step,
      restrict_year_window = "Restrict to 2014--2023",
      require_pre_post_support = "Require pre- and post-2019 firm support"),
      observations = .data$obs_after, firms = .data$firms_after, countries = .data$countries_after),
    tibble::tibble(step = "Apply baseline 22-country set", observations = nrow(analysis_data),
                   firms = dplyr::n_distinct(analysis_data$bv_d_id_number),
                   countries = dplyr::n_distinct(analysis_data$country_iso_code))
  ) |>
    dplyr::transmute(`Selection step` = .data$step, `Observations retained` = format_integer(.data$observations),
                     `Firms retained` = format_integer(.data$firms), Countries = as.character(.data$countries))
  # Report country composition separately for treatment and control groups.
  country <- analysis_data |>
    dplyr::mutate(Group = ifelse(.data$treat == 1L, "Treatment", "Control")) |>
    dplyr::group_by(.data$country_iso_code, .data$Group) |>
    dplyr::summarise(Observations = format_integer(dplyr::n()), Firms = format_integer(dplyr::n_distinct(.data$bv_d_id_number)),
                     `First year` = min(.data$year), `Last year` = max(.data$year), .groups = "drop") |>
    dplyr::rename(Country = country_iso_code)
  # Use one pre-reform mean per firm so longer histories get no extra weight.
  balance <- purrr::pmap_dfr(variable_map, function(variable, label, role) {
    firm_means <- analysis_data |>
      dplyr::filter(.data$year <= 2018L) |>
      dplyr::group_by(.data$bv_d_id_number, .data$treat) |>
      dplyr::summarise(value = mean(.data[[variable]], na.rm = TRUE), .groups = "drop") |>
      dplyr::filter(is.finite(.data$value))
    treated <- firm_means$value[firm_means$treat == 1L]; control <- firm_means$value[firm_means$treat == 0L]
    tibble::tibble(Role = role, Variable = label, `Treatment mean` = format_number(mean(treated)),
                   `Control mean` = format_number(mean(control)), Difference = format_number(mean(treated) - mean(control)),
                   `t-test p-value` = format_number(tryCatch(stats::t.test(treated, control)$p.value, error = function(e) NA_real_), 4L))
  })
  # Retain the policy-design fields needed to interpret country assignments.
  policy <- readr::read_csv(policy_path, show_col_types = FALSE) |>
    dplyr::filter(.data$include_in_main_sample) |>
    dplyr::select(dplyr::any_of(c("country", "country_iso_code", "group_main", "implementation_year", "ebitda_rule",
                                  "de_minimis", "escape_standalone", "escape_group", "carry_forward_interest")))
  list(
    sample_flow = flow,
    variable_summary = summary,
    policy_changes = policy,
    country_composition = country,
    pre_reform_balance = balance
  )
}

# `event_study_plot()` turns tidy event coefficients into the reported plot,
# rescales ratio outcomes to percentage points, and facets leverage components.
event_study_plot <- function(coefficients, analysis_id) {
  scale <- if (analysis_id %in% c("leverage", "cash")) 100 else 1
  data <- coefficients |>
    dplyr::mutate(estimate_plot = .data$estimate * scale,
                  low_plot = .data$conf_low * scale, high_plot = .data$conf_high * scale)
  plot <- ggplot2::ggplot(data, ggplot2::aes(x = .data$event_year, y = .data$estimate_plot)) +
    ggplot2::geom_hline(yintercept = 0, colour = "grey45", linewidth = .4) +
    ggplot2::geom_vline(xintercept = unique(data$reference_year), linetype = "dashed", colour = "grey55") +
    ggplot2::geom_errorbar(ggplot2::aes(ymin = .data$low_plot, ymax = .data$high_plot), width = .15) +
    ggplot2::geom_point(size = 1.8) +
    ggplot2::scale_x_continuous(breaks = sort(unique(data$event_year))) +
    ggplot2::labs(x = "Year", y = if (analysis_id == "risk") "Coefficient (EarnVol units)" else "Coefficient (percentage points)") +
    ggplot2::theme_minimal(base_size = 11) +
    ggplot2::theme(panel.grid.minor = ggplot2::element_blank())
  if (analysis_id == "leverage") plot <- plot + ggplot2::facet_wrap(~outcome_label, scales = "free_y", ncol = 2)
  plot
}
